//! `beforerunit init <shell>`: prints the integration script.

use std::path::{Path, PathBuf};

use crate::Shell;

const BASH: &str = include_str!("../shell/beforerunit.bash");
const ZSH: &str = include_str!("../shell/beforerunit.zsh");
const FISH: &str = include_str!("../shell/beforerunit.fish");

const LIB_NAME: &str = "libbeforerunit_bash.so";

pub fn exe_path() -> PathBuf {
    std::env::current_exe()
        .ok()
        .and_then(|p| p.canonicalize().ok())
        .unwrap_or_else(|| PathBuf::from("beforerunit"))
}

/// Finds the bash loadable builtin next to the binary or in standard dirs.
pub fn find_builtin() -> Option<PathBuf> {
    if let Ok(p) = std::env::var("BEFORERUNIT_BASH_BUILTIN") {
        return Some(PathBuf::from(p)).filter(|p| p.is_file());
    }
    let exe = exe_path();
    let dir = exe.parent().unwrap_or(Path::new("/"));
    let mut c = vec![
        // cargo layout: target/release/beforerunit + target/release-bash/. A
        // copy in target/release itself would be a panic=abort build.
        dir.join("../release-bash").join(LIB_NAME),
        dir.join("../lib/beforerunit").join(LIB_NAME),
        dir.join("../lib").join(LIB_NAME),
    ];
    if !dir.ends_with("target/release") && !dir.ends_with("target/debug") {
        c.push(dir.join(LIB_NAME));
    }
    if let Some(h) = std::env::var_os("HOME") {
        c.push(Path::new(&h).join(".local/lib/beforerunit").join(LIB_NAME));
    }
    c.extend(["/usr/local/lib/beforerunit", "/usr/lib/beforerunit", "/usr/lib64/beforerunit"].iter().map(|d| Path::new(d).join(LIB_NAME)));
    c.into_iter().find(|p| p.is_file()).and_then(|p| p.canonicalize().ok())
}

fn sq(s: &str) -> String {
    format!("'{}'", s.replace('\'', r"'\''"))
}

fn sq_fish(s: &str) -> String {
    format!("'{}'", s.replace('\\', r"\\").replace('\'', r"\'"))
}

/// Accepts readline-style keys like `\eb` or `\C-g`; anything else falls back.
fn toggle_key(raw: &str) -> &str {
    let ok = !raw.is_empty() && raw.len() <= 8 && raw.chars().all(|c| c.is_ascii_alphanumeric() || c == '\\' || c == '-');
    if ok && (raw.starts_with("\\e") || raw.starts_with("\\C-")) {
        raw
    } else {
        "\\eb"
    }
}

/// Human name: `\eb` -> Alt-B.
pub fn key_name(k: &str) -> String {
    if let Some(c) = k.strip_prefix("\\e") {
        format!("Alt-{}", c.to_uppercase())
    } else if let Some(c) = k.strip_prefix("\\C-") {
        format!("Ctrl-{}", c.to_uppercase())
    } else {
        k.to_string()
    }
}

fn fish_key(k: &str) -> String {
    if let Some(c) = k.strip_prefix("\\e") {
        format!("alt-{c}")
    } else if let Some(c) = k.strip_prefix("\\C-") {
        format!("ctrl-{c}")
    } else {
        "alt-b".into()
    }
}

/// fish 3 escape syntax: `\eb` stays `\eb`, `\C-g` becomes `\cg`.
fn fish3_key(k: &str) -> String {
    if let Some(c) = k.strip_prefix("\\C-") {
        format!("\\c{c}")
    } else if k.starts_with("\\e") {
        k.to_string()
    } else {
        "\\eb".into()
    }
}

fn ble_key(k: &str) -> String {
    if let Some(c) = k.strip_prefix("\\e") {
        format!("M-{c}")
    } else if let Some(c) = k.strip_prefix("\\C-") {
        format!("C-{c}")
    } else {
        "M-b".into()
    }
}

/// Editing functions that get a refresh after them, with their keys.
const EDIT_KEYS: &[(&str, &[&str])] = &[
    ("backward-delete-char", &[r"\C-?", r"\C-h"]),
    ("delete-char", &[r"\e[3~"]),
    ("unix-word-rubout", &[r"\C-w"]),
    ("backward-kill-word", &[r"\e\C-?"]),
    ("kill-word", &[r"\ed"]),
    ("unix-line-discard", &[r"\C-u"]),
    ("kill-line", &[r"\C-k"]),
    ("yank", &[r"\C-y"]),
    ("yank-pop", &[r"\ey"]),
    ("complete", &[r"\C-i"]),
    ("previous-history", &[r"\e[A", r"\eOA", r"\C-p"]),
    ("next-history", &[r"\e[B", r"\eOB", r"\C-n"]),
    ("undo", &[r"\C-_"]),
    ("yank-last-arg", &[r"\e.", r"\e_"]),
    ("transpose-chars", &[r"\C-t"]),
];

/// The readline macro bindings, loaded with one `bind -f` (separate `bind`
/// calls cost ~15us each). Each printable key runs self-insert through
/// `\C-x\C-b_<key>` (self-insert inserts the last key of the sequence) and
/// then the paint hook.
pub fn bash_inputrc() -> String {
    let mut s = String::from("# Generated by `beforerunit init bash`.\n");
    let mut arg = |a: String| {
        s.push_str(&a);
        s.push('\n');
    };
    for b in 0x20u8..0x7f {
        let c = match b as char {
            c @ ('"' | '\\') => format!("\\{c}"),
            c => c.to_string(),
        };
        arg(format!(r#""\C-x\C-b_{c}": self-insert"#));
        arg(format!(r#""{c}": "\C-x\C-b_{c}\C-x\C-b=""#));
    }
    for (i, (func, keys)) in EDIT_KEYS.iter().enumerate() {
        let tag = (b'a' + i as u8) as char;
        arg(format!(r#""\C-x\C-b{tag}": {func}"#));
        for k in *keys {
            arg(format!(r#""{k}": "\C-x\C-b{tag}\C-x\C-b=""#));
        }
    }
    for a in [
        r#""\C-x\C-bL": clear-screen"#,
        r#""\C-l": "\C-x\C-bL\C-x\C-b+""#,
        r#""\C-x\C-bM": accept-line"#,
        r#""\C-m": "\C-x\C-b-\C-x\C-bM""#,
        r#""\C-j": "\C-x\C-b-\C-x\C-bM""#,
    ] {
        arg(a.to_string());
    }
    s
}

/// Writes the inputrc into the cache dir when it changed; None if unwritable.
fn bash_inputrc_file() -> Option<PathBuf> {
    let dir = beforerunit_core::store::cache_dir();
    let path = dir.join("bash-keys.inputrc");
    let want = bash_inputrc();
    if std::fs::read_to_string(&path).ok().as_deref() != Some(want.as_str()) {
        std::fs::create_dir_all(&dir).ok()?;
        let tmp = path.with_extension(format!("tmp{}", std::process::id()));
        std::fs::write(&tmp, &want).ok()?;
        std::fs::rename(&tmp, &path).ok()?;
    }
    Some(path)
}

pub fn script(shell: Shell, no_builtin: bool) -> String {
    let compiled = beforerunit_core::store::load_or_compile();
    let ui = &compiled.config.ui;
    let key = toggle_key(&ui.toggle_key);
    let bin = exe_path().to_string_lossy().into_owned();
    let display = ui.display.as_str();
    match shell {
        Shell::Bash => {
            let lib = if no_builtin { None } else { find_builtin() };
            BASH.replace("@BIN@", &sq(&bin))
                .replace("@LIB@", &sq(&lib.map(|p| p.to_string_lossy().into_owned()).unwrap_or_default()))
                .replace("@DISPLAY@", display)
                .replace("@TOGGLE_BLE@", &ble_key(key))
                .replace("@TOGGLE_NAME@", &key_name(key))
                .replace("@TOGGLE@", key)
                .replace("@INPUTRC@", &sq(&bash_inputrc_file().map(|p| p.to_string_lossy().into_owned()).unwrap_or_default()))
        }
        Shell::Zsh => ZSH
            .replace("@BIN@", &sq(&bin))
            .replace("@SOCK@", &sq(&beforerunit_core::store::socket_path().to_string_lossy()))
            .replace("@DISPLAY@", display)
            .replace("@TOGGLE_NAME@", &key_name(key))
            .replace("@TOGGLE@", &sq(key)),
        Shell::Fish => FISH
            .replace("@BIN@", &sq_fish(&bin))
            .replace("@DISPLAY@", display)
            .replace("@TOGGLE_NAME@", &key_name(key))
            .replace("@TOGGLE3@", &fish3_key(key))
            .replace("@TOGGLE@", &fish_key(key)),
    }
}

pub fn run(shell: Shell, no_builtin: bool, inputrc: bool) -> i32 {
    if inputrc {
        print!("{}", bash_inputrc());
    } else {
        print!("{}", script(shell, no_builtin));
    }
    0
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn keys() {
        assert_eq!(toggle_key("\\eb"), "\\eb");
        assert_eq!(toggle_key("$(rm)"), "\\eb");
        assert_eq!(key_name("\\eb"), "Alt-B");
        assert_eq!(fish_key("\\C-g"), "ctrl-g");
        assert_eq!(fish3_key("\\C-g"), "\\cg");
        assert_eq!(fish3_key("\\eb"), "\\eb");
        assert_eq!(ble_key("\\eb"), "M-b");
    }

    #[test]
    fn quoting() {
        assert_eq!(sq("a'b"), r"'a'\''b'");
        assert_eq!(sq_fish(r"a'b\c"), r"'a\'b\\c'");
    }

    #[test]
    fn no_placeholders_left() {
        for s in [Shell::Bash, Shell::Zsh, Shell::Fish] {
            let out = script(s, true);
            for p in ["@BIN@", "@LIB@", "@SOCK@", "@DISPLAY@", "@TOGGLE@", "@TOGGLE_NAME@", "@TOGGLE_BLE@", "@INPUTRC@", "@TOGGLE3@"] {
                assert!(!out.contains(p), "{s:?} still has {p}");
            }
        }
    }
}
